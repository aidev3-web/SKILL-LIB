HR_RE_2 = re.compile(r"^\s*(-{3,}|\*{3,}|_{3,})\s*$")
QUOTE_RE = re.compile(r"^\s*>\s?")
DATE_KEY_RE = re.compile(r"^(ngày|date|ngay)\b", re.IGNORECASE)


def detect_lang(text):
    return "vi" if VI_CHARS_RE.search(text or "") else "en"


def detect_doc_type(title, body):
    t = str(title or "").strip()
    if not t:
        t = str(body or "")[:600]
    t = t.lower()
    if re.search("biên bản|meeting minutes|minutes of meeting", t):
        return "meeting-minutes"
    if re.search("đề xuất|proposal|báo giá|quotation", t):
        return "proposal"
    if re.search("hướng dẫn|how-to|how to|quy trình", t):
        return "how-to"
    if re.search("bản tin|newsletter", t):
        return "newsletter"
    if re.search("đặc tả|specification|technical spec", t):
        return "spec"
    if re.search("memo|ghi nhớ nội bộ", t):
        return "memo"
    return "report"


def looks_like_date(value):
    v = str(value).strip()
    return bool(re.match(r"^\d{1,4}[-/.]\d{1,2}[-/.]\d{1,4}$", v)
                or re.match(r"^\d{1,2}\s+tháng\s+\d{1,2},?\s*\d{4}$", v, re.IGNORECASE))


def split_row(line):
    s = line.strip()
    if s[:1] == "|":
        s = s[1:]
    if s[-1:] == "|":
        s = s[:-1]
    cells = re.split(r"(?<!\\)\|", s)
    return [c.replace("\\|", "|").strip() for c in cells]


def is_table_row(line):
    return line.count("|") >= 2


def indent_width(ws):
    return sum(4 if ch == "\t" else 1 for ch in ws)


def list_entry(line):
    o = ORDERED_RE.match(line)
    if o:
        return {"indent": indent_width(o.group(1)), "ordered": True, "text": o.group(3).strip()}
    b = BULLET_RE.match(line)
    if b:
        return {"indent": indent_width(b.group(1)), "ordered": False, "text": b.group(2).strip()}
    return None


def build_list(entries):
    root = {"indent": entries[0]["indent"], "items": []}
    stack = [root]
    for e in entries:
        while len(stack) > 1 and e["indent"] < stack[-1]["indent"]:
            stack.pop()
        top = stack[-1]
        if e["indent"] > top["indent"] and top["items"]:
            parent = top["items"][-1]
            if isinstance(parent, str):
                parent = {"text": parent, "items": []}
                top["items"][-1] = parent
            if e["ordered"]:
                parent["ordered"] = True
            child = {"indent": e["indent"], "items": parent["items"]}
            stack.append(child)
            top = child
        top["items"].append(e["text"])
    return root["items"]


def parse_markdown(text, title=None, doc_type=None):
    """Markdown / plain text -> model. Mirrors parseMarkdown() in core.js."""
    text = str(text or "")
    lines = re.sub(r"\r\n?", "\n", text).split("\n")
    model = {"title": "", "subtitle": "", "date": "", "doc_type": "",
             "lang": detect_lang(text), "sections": []}
    sections = []
    state = {"current": None}
    pending = []

    def target():
        if state["current"] is None:
            state["current"] = {"heading": "", "level": 2, "blocks": []}
            sections.append(state["current"])
        return state["current"]

    def flush_paragraph():
        joined = re.sub(r"\s+", " ", " ".join(pending)).strip()
        if joined:
            target()["blocks"].append({"type": "paragraph", "text": joined})
        pending.clear()

    i = 0
    while i < len(lines):
        line = lines[i]
        trimmed = line.strip()

        fence_open = FENCE_RE.match(line)
        if fence_open or FENCE_ANY_RE.match(line):
            flush_paragraph()
            fence = []
            i += 1
            while i < len(lines) and not FENCE_CLOSE_RE.match(lines[i]):
                fence.append(lines[i])
                i += 1
            if fence:
                block = {"type": "code", "text": "\n".join(fence)}
                if fence_open and fence_open.group(1):
                    block["lang"] = fence_open.group(1)
                target()["blocks"].append(block)
            i += 1
            continue
        if not trimmed:
            flush_paragraph()
            i += 1
            continue

        head = HEADING_RE.match(line)
        if head:
            flush_paragraph()
            level, heading = len(head.group(1)), head.group(2).strip()
            if level == 1 and not model["title"]:
                model["title"] = heading
            elif level <= 2:
                state["current"] = {"heading": heading, "level": 2, "blocks": []}
                sections.append(state["current"])
            else:
                target()["blocks"].append({"type": "heading", "text": heading, "level": min(level, 6)})
            i += 1
            continue
        if HR_RE_1.match(line) or HR_RE_2.match(trimmed):
            flush_paragraph()
            target()["blocks"].append({"type": "hr"})
            i += 1
            continue
        image = IMAGE_RE.match(line)
        if image:
            flush_paragraph()
            block = {"type": "image", "src": image.group(2), "alt": image.group(1).strip()}
            if image.group(3):
                block["caption"] = image.group(3)
            target()["blocks"].append(block)
            i += 1
            continue
        if QUOTE_RE.match(line):
            flush_paragraph()
            quoted = []
            while i < len(lines) and QUOTE_RE.match(lines[i]):
                quoted.append(QUOTE_RE.sub("", lines[i], count=1).strip())
                i += 1
            quote_text = " ".join(q for q in quoted if q).strip()
            if quote_text:
                target()["blocks"].append({"type": "quote", "text": quote_text})
            continue
        if is_table_row(line):
            start, rows = i, []
            while i < len(lines) and is_table_row(lines[i]):
                rows.append(lines[i])
                i += 1
            if len(rows) >= 2 and TABLE_SEP_RE.match(rows[1]):
                flush_paragraph()
                target()["blocks"].append({"type": "table", "headers": split_row(rows[0]),
                                           "rows": [split_row(r) for r in rows[2:]]})
            else:
                pending.extend(lines[start:i])
            continue
        first = list_entry(line)
        if first:
            flush_paragraph()
            entries = []
            while i < len(lines):
                e = list_entry(lines[i])
                if not e:
                    break
                # a top-level item of the other kind starts a new list
                if e["indent"] <= first["indent"] and e["ordered"] != first["ordered"]:
                    break
                entries.append(e)
                i += 1
            target()["blocks"].append({"type": "list", "ordered": first["ordered"], "items": build_list(entries)})
            continue
        if KV_RE.match(line) and len(trimmed) < 120:
            kv_lines = []
            while i < len(lines) and KV_RE.match(lines[i]) and len(lines[i].strip()) < 120:
                kv_lines.append(KV_RE.match(lines[i]))
                i += 1
            flush_paragraph()
            target()["blocks"].append({"type": "kv",
                                       "pairs": [[m.group(1).strip(), m.group(2).strip()] for m in kv_lines]})
            continue
        pending.append(trimmed)
        i += 1
    flush_paragraph()

    for section in sections:
        for block in section.get("blocks") or []:
            if block["type"] != "kv":
                continue
            for pair in block["pairs"]:
                if not model["date"] and DATE_KEY_RE.match(pair[0]) and looks_like_date(pair[1]):
                    model["date"] = pair[1]

    model["doc_type"] = detect_doc_type(model["title"], text)
    model["sections"] = [s for s in sections if s["heading"] or s["blocks"]]
    if title:
        model["title"] = title
    if doc_type:
        model["doc_type"] = doc_type
    return model


