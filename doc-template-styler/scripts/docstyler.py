def w(tag):
    return "{%s}%s" % (W, tag)


BOLD_HEADING_RE = re.compile(r"^\*\*(.+)\*\*$")
MD_SPECIAL_RE = re.compile(r"([\\`*_\[\]])")
LINE_START_RE = re.compile(r"^(\s*)(#|>|[-*+•]\s|\d{1,3}[.)]\s|!\[|```)")


def escape_line_start(text):
    """A body paragraph that happens to start like Markdown ("1. ", "# ", "- ")
    must stay a paragraph: escape the marker so the parser leaves it alone and
    the renderer shows it as typed."""
    m = LINE_START_RE.match(text)
    if not m:
        return text
    if m.group(2)[0].isdigit():
        return re.sub(r"^(\s*\d{1,3})([.)])", r"\1\\\2", text, count=1)
    return text[:m.start(2)] + "\\" + text[m.start(2):]


def md_escape(text):
    return MD_SPECIAL_RE.sub(r"\\\1", text)


def _on(el):
    """A w:b / w:i toggle: present and not switched off."""
    if el is None:
        return False
    return el.get(w("val"), "true").lower() not in ("0", "false", "off", "none")


def _wrap(text, bold, italic):
    if not text.strip() or not (bold or italic):
        return text
    lead = text[:len(text) - len(text.lstrip())]
    trail = text[len(text.rstrip()):]
    core = text.strip()
    mark = ("**" if bold else "") + ("*" if italic else "")
    return "%s%s%s%s%s" % (lead, mark, core, mark[::-1], trail)


class Docx:
    def __init__(self, path):
        self.zip = zipfile.ZipFile(path)
        self.rels = self._rels("word/_rels/document.xml.rels")
        self.styles = self._styles()
        self.numbering = self._numbering()
        self.warnings = []

    def _read(self, name):
        try:
            return self.zip.read(name)
        except KeyError:
            return None

    def _rels(self, name):
        data = self._read(name)
        out = {}
        if data:
            for rel in ET.fromstring(data).findall("{%s}Relationship" % PKG_REL):
                out[rel.get("Id")] = (rel.get("Target"), rel.get("TargetMode"))
        return out

    def _styles(self):
        """styleId -> lower-case name; also fills self.style_numbering with
        the numbering a style carries itself (styleId -> (numId, ilvl))."""
        data = self._read("word/styles.xml")
        out = {}
        self.style_numbering = {}
        if data:
            for style in ET.fromstring(data).findall(w("style")):
                sid = style.get(w("styleId"))
                name = style.find(w("name"))
                out[sid] = (name.get(w("val")) if name is not None else "").lower()
                num = style.find("%s/%s" % (w("pPr"), w("numPr")))
                if num is not None and num.find(w("numId")) is not None:
                    ilvl = num.find(w("ilvl"))
                    self.style_numbering[sid] = (num.find(w("numId")).get(w("val")),
                                                 ilvl.get(w("val")) if ilvl is not None else None)
        return out

    def _numbering(self):
        """numId -> {ilvl: ordered?}"""
        data = self._read("word/numbering.xml")
        if not data:
            return {}
        root = ET.fromstring(data)
        abstract = {}
        for an in root.findall(w("abstractNum")):
            levels = {}
            for lvl in an.findall(w("lvl")):
                fmt = lvl.find(w("numFmt"))
                value = fmt.get(w("val")) if fmt is not None else "bullet"
                levels[lvl.get(w("ilvl"))] = value not in ("bullet", "none")
            abstract[an.get(w("abstractNumId"))] = levels
        out = {}
        for num in root.findall(w("num")):
            ref = num.find(w("abstractNumId"))
            if ref is not None:
                out[num.get(w("numId"))] = abstract.get(ref.get(w("val")), {})
        return out

    # --- paragraph content ---

    def style_of(self, p):
        ppr = p.find(w("pPr"))
        sid = ""
        if ppr is not None and ppr.find(w("pStyle")) is not None:
            sid = ppr.find(w("pStyle")).get(w("val")) or ""
        return sid, self.styles.get(sid, sid.lower())

    def runs_text(self, parent):
        """Markdown for the runs under a paragraph or hyperlink, merging
        neighbouring runs that share formatting."""
        pieces = []  # (text, bold, italic)
        for child in parent:
            if child.tag == w("r"):
                rpr = child.find(w("rPr"))
                bold = _on(rpr.find(w("b"))) if rpr is not None else False
                italic = _on(rpr.find(w("i"))) if rpr is not None else False
                for node in child:
                    if node.tag == w("t"):
                        pieces.append((md_escape(node.text or ""), bold, italic))
                    elif node.tag == w("tab"):
                        pieces.append((" ", bold, italic))
                    elif node.tag in (w("br"), w("cr")):
                        pieces.append((" ", bold, italic))
            elif child.tag == w("hyperlink"):
                label = self.runs_text(child)
                target = self.rels.get(child.get("{%s}id" % R), (None, None))[0]
                anchor = child.get(w("anchor"))
                url = target or ("#" + anchor if anchor else "")
                pieces.append(("[%s](%s)" % (label, url.replace(" ", "%20")) if url and label.strip() else label,
                               False, False))
            elif child.tag in (w("ins"), w("smartTag"), w("sdt"), w("sdtContent"), w("fldSimple")):
                pieces.append((self.runs_text(child), False, False))
        merged = []
        for text, bold, italic in pieces:
            if merged and merged[-1][1] == bold and merged[-1][2] == italic:
                merged[-1] = (merged[-1][0] + text, bold, italic)
            else:
                merged.append((text, bold, italic))
        return "".join(_wrap(t, b, i) for t, b, i in merged)

    def images_in(self, p):
        out = []
        for blip in p.iter("{%s}blip" % A):
            rid = blip.get("{%s}embed" % R)
            target = self.rels.get(rid, (None, None))[0]
            if not target:
                continue
            name = posixpath.normpath(posixpath.join("word", target))
            data = self._read(name)
            if data is None:
                self.warnings.append("image %s is linked, not embedded - skipped" % target)
                continue
            mime = mimetypes.guess_type(name)[0] or "image/png"
            if not mime.startswith("image/") or mime in ("image/x-emf", "image/x-wmf", "image/emf", "image/wmf"):
                self.warnings.append("image %s is %s, which browsers cannot show - skipped" % (target, mime))
                continue
            alt = ""
            for doc_pr in p.iter("{%s}docPr" % WP):
                alt = doc_pr.get("descr") or doc_pr.get("title") or ""
                break
            out.append("![%s](data:%s;base64,%s)" % (alt.replace("]", ")").replace("\n", " "), mime,
                                                     base64.b64encode(data).decode("ascii")))
        return out

    def list_info(self, p, style_name):
        ppr = p.find(w("pPr"))
        num = ppr.find(w("numPr")) if ppr is not None else None
        if num is not None and num.find(w("numId")) is not None:
            num_id = num.find(w("numId")).get(w("val"))
            if num_id == "0":
                return None
            ilvl_el = num.find(w("ilvl"))
            ilvl = ilvl_el.get(w("val")) if ilvl_el is not None else "0"
            ordered = self.numbering.get(num_id, {}).get(ilvl, False)
            return int(ilvl), ordered
        # numbering that comes from the paragraph style (List Bullet, List Number 2 ...)
        depth = re.search(r"(\d)$", style_name)
        ilvl = int(depth.group(1)) - 1 if depth and style_name.startswith("list ") else 0
        sid = self.style_of(p)[0]
        if sid in self.style_numbering:
            num_id, style_ilvl = self.style_numbering[sid]
            level = style_ilvl if style_ilvl is not None else str(ilvl)
            if num_id != "0":
                return int(level), self.numbering.get(num_id, {}).get(level, style_name.startswith("list number"))
        if style_name.startswith("list number"):
            return ilvl, True
        if style_name.startswith("list bullet") or style_name == "list paragraph":
            return ilvl, False
        return None

    # --- document ---

    def to_markdown(self):
        body = ET.fromstring(self.zip.read("word/document.xml")).find(w("body"))
        out = []
        subtitle = ""
        prev_kind = None

        def emit(line, kind):
            nonlocal prev_kind
            # keep list items and Key: Value lines contiguous; everything
            # else is its own paragraph
            if out and not (kind == prev_kind and kind in ("list", "kv")):
                out.append("")
            out.append(line)
            prev_kind = kind

        for el in body:
            if el.tag == w("tbl"):
                rows = []
                for tr in el.findall(w("tr")):
                    cells = []
                    for tc in tr.findall(w("tc")):
                        text = " ".join(self.runs_text(p).strip() for p in tc.iter(w("p")))
                        cells.append(re.sub(r"\s+", " ", text).strip().replace("|", "\\|"))
                    rows.append(cells)
                if not rows:
                    continue
                width = max(len(r) for r in rows)
                rows = [r + [""] * (width - len(r)) for r in rows]
                if width < 2:
                    for r in rows:
                        if r[0]:
                            emit(r[0], "p")
                    continue
                lines = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * width]
                lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
                emit("\n".join(lines), "table")
                continue
            if el.tag != w("p"):
                continue

            sid, style = self.style_of(el)
            text = re.sub(r"[ \t]+", " ", self.runs_text(el)).strip()
            images = self.images_in(el)

            level = None
            m = re.match(r"^(?:heading|đề mục)\s*(\d)$", style) or re.match(r"^heading(\d)$", sid.lower())
            if m:
                level = int(m.group(1))
            if style == "title" or sid.lower() == "title":
                level = 1
            if (style == "subtitle" or sid.lower() == "subtitle") and text:
                subtitle = subtitle or text
                continue

            # a short paragraph that is bold from end to end, not a sentence and
            # not a list item, is a heading typed by hand ("**1. Thông tin**")
            if text and not level and not self.list_info(el, style) and BOLD_HEADING_RE.match(text):
                inner = BOLD_HEADING_RE.match(text).group(1).strip()
                if len(inner) <= 90 and not inner.endswith((",", ".", ":", ";")) and "**" not in inner:
                    emit("## " + inner, "h")
                    for image in images:
                        emit(image, "image")
                    continue
            if text:
                if level:
                    emit("#" * min(level, 6) + " " + text, "h")
                elif "quote" in style:
                    emit("> " + text, "quote")
                else:
                    info = self.list_info(el, style)
                    if info:
                        ilvl, ordered = info
                        emit("  " * ilvl + ("1. " if ordered else "- ") + text, "list")
                    else:
                        text = escape_line_start(text)
                        emit(text, "kv" if KV_RE.match(text) and len(text) < 120 else "p")
            for image in images:
                emit(image, "image")
        return "\n".join(out) + "\n", subtitle


def _bold_cell(cell):
    m = BOLD_HEADING_RE.match(cell or "")
    return m.group(1).strip() if m and "**" not in m.group(1) else None


def tables_to_kv(model):
    """A two-column Word table whose first column is bold throughout is a list
    of labelled values (Vị trí | SE Intern), not a data table: make it kv."""
    for section in model.get("sections") or []:
        for i, block in enumerate(section.get("blocks") or []):
            if block.get("type") != "table":
                continue
            rows = [block.get("headers") or []] + (block.get("rows") or [])
            if not rows or any(len(r) != 2 for r in rows):
                continue
            keys = [_bold_cell(r[0]) for r in rows]
            if all(keys):
                section["blocks"][i] = {"type": "kv", "pairs": [[k, r[1]] for k, r in zip(keys, rows)]}
    return model


def import_docx(path, title=None, doc_type=None):
    doc = Docx(path)
    markdown, subtitle = doc.to_markdown()
    model = tables_to_kv(parse_markdown(markdown, title=title, doc_type=doc_type))
    if subtitle and not model.get("subtitle"):
        model["subtitle"] = subtitle
    return model, doc.warnings


# ------------------------------------------------------------- outline ----

def _text(value):
    if isinstance(value, dict) and ("vi" in value or "en" in value):
        return str(value.get("vi") or value.get("en") or "")
    return "" if value is None else str(value)


def _count_items(items):
    n = 0
    for item in items or []:
        n += 1
        if isinstance(item, dict) and not ("vi" in item or "en" in item):
            n += _count_items(item.get("items"))
    return n


def describe(block):
    kind = (block.get("type") or "paragraph").lower()
    if kind == "list":
        nested = any(isinstance(i, dict) and "items" in i for i in block.get("items") or [])
        return "list(%s%d%s)" % ("ordered, " if block.get("ordered") else "",
                                 _count_items(block.get("items")), ", nested" if nested else "")
    if kind == "table":
        return "table(%d rows)" % len(block.get("rows") or [])
    if kind == "heading":
        return "heading(h%d)" % int(block.get("level", 3))
    if kind == "callout":
        return "callout(%s)" % block.get("tone", "info")
    if kind == "kv":
        return "kv(%d)" % len(block.get("pairs") or [])
    if kind == "code":
        return "code(%s)" % (block.get("lang") or "text")
    if kind == "image":
        src = str(block.get("src") or "")
        return "image(%s)" % ("embedded" if src.startswith("data:") else src or "no src")
    return kind


def outline(model):
    lines = []
    title = _text(model.get("title"))
    lines.append("title: %s" % (title or "(none)"))
    if model.get("subtitle"):
        lines.append("subtitle: %s" % _text(model.get("subtitle")))
    lines.append("doc_type: %s | lang: %s%s" % (model.get("doc_type") or "report", _text(model.get("lang")) or "vi",
                                                 " | date: %s" % _text(model["date"]) if model.get("date") else ""))
    sections = model.get("sections") or []
    width = min(max([len(_text(s.get("heading")) or "(no heading)") for s in sections] + [10]) + 4, 48)
    for n, section in enumerate(sections, 1):
        heading = _text(section.get("heading")) or "(no heading)"
        if len(heading) > width - 4:
            heading = heading[:width - 5] + "…"
        blocks = ", ".join(describe(b) for b in section.get("blocks") or []) or "(empty)"
        lines.append("%2d. %s %s %s" % (n, heading, "." * max(3, width - len(heading)), blocks))
    return "\n".join(lines)


