LANG_KEYS = ("vi", "en")
TEMPLATE_ID_RE = re.compile(r'\bid="([^"{}]+)"')

# Inline formatting: a small, safe subset of Markdown. Code spans and backslash
# escapes are set aside first so nothing inside them is formatted.
INLINE_PROTECT_RE = re.compile(r"\\([\\`*_\[\]()#>+\-.!|])|`([^`\n]+)`")
LINK_RE = re.compile(r"\[([^\]\n]+)\]\(([^)\s]+)\)")
